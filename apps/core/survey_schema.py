def _o(value, label, hint=''):
    return {'value': value, 'label': label, 'hint': hint}


def _q(qid, label, qtype, hint='', options=None, items=None, sub=None, note='', image='',
       numbered=True, optional_hint=''):
    return {
        'id': qid, 'label': label, 'type': qtype, 'hint': hint,
        'options': options or [], 'items': items or [], 'sub': sub or [],
        'note': note, 'image': image, 'numbered': numbered, 'optional_hint': optional_hint,
    }


def _sub(qid, label, qtype, options=None):
    """سؤال فرعي يتبع سؤالاً رئيسياً (بلا ترقيم)."""
    return _q(qid, label, qtype, options=options, numbered=False)


