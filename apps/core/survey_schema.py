def get_sections(form_type):
    return SECTIONS[form_type]


def iter_questions(form_type):
    """كل الأسئلة بما فيها الفرعية، بالترتيب."""
    for sec in get_sections(form_type):
        for q in sec['questions']:
            yield q
            for s in q['sub']:
                yield s


def numbered_sections(form_type):
    """نسخة من الأقسام مع رقم تسلسلي (q['num']) للأسئلة المرقّمة."""
    out, n = [], 0
    for sec in get_sections(form_type):
        qs = []
        for q in sec['questions']:
            q = dict(q)
            if q['numbered']:
                n += 1
                q['num'] = n
            qs.append(q)
        out.append({'title': sec['title'], 'questions': qs})
    return out


def parse_answers(form_type, post):
    """يحوّل بيانات POST إلى قاموس إجابات آمن (يتجاهل القيم غير المعرّفة)."""
    answers = {}
    for q in iter_questions(form_type):
        qid, t = q['id'], q['type']
        key = f'q_{qid}'
        valid = {o['value'] for o in q['options']}
        if t in ('text', 'textarea', 'number'):
            val = (post.get(key) or '').strip()
            answers[qid] = val[:2000 if t == 'textarea' else 200]
        elif t == 'radio':
            val = post.get(key) or ''
            answers[qid] = val if val in valid else ''
        elif t == 'checkbox':
            answers[qid] = [v for v in post.getlist(key) if v in valid]
        elif t == 'count_list':
            rows = {}
            for it in q['items']:
                on = post.get(f'{key}__{it["value"]}') == '1'
                cnt = (post.get(f'{key}__{it["value"]}__n') or '').strip()[:10]
                rows[it['value']] = {'on': on or bool(cnt), 'count': cnt}
            answers[qid] = rows
    return answers
